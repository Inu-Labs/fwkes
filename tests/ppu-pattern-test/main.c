typedef struct Emulator {
    Ppu ppu;

    SDL_Window *win;
    SDL_Renderer *renderer;
    SDL_Texture *canvas;
    uint32_t framebuffer[240][256];
    bool quit;
} Emulator;

static void prepare_canvas(Emulator *self) {
    for (int y = 0; y < PPU_HEIGHT; ++y) {
        for (int x = 0; x < PPU_WIDTH; ++x) {
            self->framebuffer[y][x] = g_colors[self->ppu.framebuffer[x][y]];
        }
    }

    SDL_UpdateTexture(
        self->canvas, NULL, self->framebuffer, 256 * sizeof(uint32_t)
    );

    self->ppu.frame_done = false;
}

static void draw_grid(Emulator *self) {
    for (int y = 0; y < 240 * 3; y += 8 * 3) {
        for (int x = 0; x < 256 * 3; x += 8 * 3) {
            if ((x % 16 * 3) == 0 && (y % 16 * 3) == 0) {
                SDL_FRect dims = {(float) x, (float) y, 3, 3};

                SDL_SetRenderDrawColor(self->renderer, 0xff, 0x00, 0x00, 0xff);
                SDL_RenderRect(self->renderer, &dims);
            }
        }
    }
}

void emu_init(Emulator *self) {
    memset(self, 0, sizeof(*self));

    // trace_add_cat_filter(TRACE_PPU);
    // log_add_cat_filter(LOG_PPU);
    // log_add_cat_filter(LOG_BUS);

    self->ppu.chr = g_chr;
    self->ppu.mirroring = MIRRORING_HORIZONTAL;

    uint16_t y0 = 0;
    uint16_t x0 = 0;
    for (uint16_t y = 0; y < 30; y++) {
        for (uint16_t x = 0; x < 32; x++) {
            ppu_write(
                &self->ppu, PPU_NT0 + (y0 * 32 + x0), (y * 32 + x) & 0xff
            );

            if (x0 == 15) {
                x0 = 0;
                ++y0;
            } else {
                ++x0;
            }
        }
    }

    for (uint8_t y = 0; y < 8; ++y) {
        for (uint8_t x = 0; x < 8; ++x) {
            ppu_write(&self->ppu, PPU_AT0 + (y * 8 + x), 0x1b);
        }
    }

    static uint8_t pallete_colors[] = {
        0x0f, 0x15, 0x2c, 0x12, 0x0f, 0x27, 0x02, 0x17, 0x0f, 0x30, 0x36,
        0x06, 0x0f, 0x30, 0x2c, 0x24, 0x0f, 0x02, 0x36, 0x16, 0x0f, 0x30,
        0x27, 0x24, 0x0f, 0x16, 0x30, 0x37, 0x0f, 0x06, 0x27, 0x02,
    };

    for (int i = 0; i < 32; ++i) {
        self->ppu.palletes[i] = pallete_colors[i];
    }
}

void emu_render(Emulator *self) {
    prepare_canvas(self);
    SDL_RenderTexture(self->renderer, self->canvas, NULL, NULL);
}

void emu_run(Emulator *self) {
    while (!self->quit) {
        SDL_Event ev;

        while (SDL_PollEvent(&ev)) {
            switch (ev.type) {
            case SDL_EVENT_QUIT:
                return;
            case SDL_EVENT_KEY_DOWN:
                if (ev.key.scancode == SDL_SCANCODE_Q) {
                    self->quit = true;
                }

                break;
            default:
                break;
            }
        }

        SDL_SetRenderDrawColor(self->renderer, 0x00, 0x00, 0x00, 0xff);
        SDL_RenderClear(self->renderer);

        emu_render(self);
        draw_grid(self);

        SDL_RenderPresent(self->renderer);

        SDL_DelayPrecise(20000000);
    }
}

int main(void) {
    if (!SDL_Init(SDL_INIT_VIDEO)) {
        return -1;
    }

    Emulator emu;
    emu_init(&emu);

    if (!SDL_CreateWindowAndRenderer(
            "PPU pattern test", 256 * 3, 240 * 3, 0, &emu.win, &emu.renderer
        )) {
        SDL_Quit();

        return -1;
    }

    emu.canvas = SDL_CreateTexture(
        emu.renderer, SDL_PIXELFORMAT_RGBA8888, SDL_TEXTUREACCESS_STATIC, 256,
        240
    );

    SDL_SetTextureScaleMode(emu.canvas, SDL_SCALEMODE_NEAREST);

    emu_run(&emu);

    SDL_DestroyTexture(emu.canvas);
    SDL_DestroyRenderer(emu.renderer);
    SDL_DestroyWindow(emu.win);

    SDL_Quit();

    return 0;
}
